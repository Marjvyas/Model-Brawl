class ModelDetailsRequest(BaseModel):
    model: str

@app.post("/api/model_details/{task_id}")
def get_model_details(task_id: str, req: ModelDetailsRequest):
    """
    Retrains ONE requested model on the cached training matrices and returns
    the same payload shape as `best_model` (CV R², final R²/RMSE, verdict,
    recommendation and chart visuals). Lets the results page display any
    leaderboard model dynamically without re-running the whole tournament.
    Sync def on purpose: runs in FastAPI's thread pool so the event loop
    is not blocked while the model trains.
    """
    if task_id not in tasks:
        raise HTTPException(status_code=404, detail="Task not found.")
    task = tasks[task_id]
    model_name = (req.model or "").strip()

    registry = ml_pipeline.build_model_registry()
    if model_name not in registry:
        raise HTTPException(
            status_code=400,
            detail=f"Unknown model '{model_name}'. Available: {', '.join(registry)}"
        )

    cache_dir = os.path.join(UPLOAD_DIR, task_id)
    x_path = os.path.join(cache_dir, "X_train.parquet")
    if not os.path.exists(x_path):
        raise HTTPException(status_code=404, detail="Cached dataset not found. Please re-run the pipeline.")

    # Per-model cache so toggling between leaderboard models is instant
    details_cache = task.setdefault("model_details_cache", {})
    if model_name in details_cache:
        return details_cache[model_name]

    try:
        X_train = pd.read_parquet(x_path)
        X_test = pd.read_parquet(os.path.join(cache_dir, "X_test.parquet"))
        y_train = pd.read_parquet(os.path.join(cache_dir, "y_train.parquet")).iloc[:, 0]
        y_test = pd.read_parquet(os.path.join(cache_dir, "y_test.parquet")).iloc[:, 0]

        # Keep the same feature set the tournament used (excluded features were dropped there)
        excluded = task.get("excluded_features") or []
        if excluded:
            cols_to_drop = [c for c in excluded if c in X_train.columns]
            if cols_to_drop:
                X_train = X_train.drop(columns=cols_to_drop)
                X_test = X_test.drop(columns=cols_to_drop)

        if X_train.shape[1] == 0:
            raise ValueError("No features available: every feature was excluded.")

        preprocessing_report = task.get("preprocessing_report") or {}

        _, final_metrics = ml_pipeline.final_exam(
            model_name,
            registry[model_name],
            X_train, y_train, X_test, y_test,
            target_transform_applied=preprocessing_report.get("target_transform_applied"),
            log=lambda msg: None,
        )

        # CV score straight from the stored leaderboard
        results_obj = task.get("results") or {}
        entry = next(
            (m for m in (results_obj.get("leaderboard") or []) if m.get("model") == model_name),
            None,
        )
        cv_r2 = entry.get("cv_r2_mean") if entry else None

        payload = {
            "name": model_name,
            "cv_r2": cv_r2,
            "final_r2": final_metrics["final_r2"],
            "final_rmse": final_metrics["final_rmse"],
            "recommendation": ml_pipeline.recommendation_text_for(model_name),
            "verdict": final_metrics["verdict"],
            "visuals": final_metrics.get("visuals", {}),
        }
        details_cache[model_name] = payload
        return payload

    except ValueError as e:
        raise HTTPException(status_code=400, detail=str(e))
    except Exception as e:
        import traceback
        traceback.print_exc()
        raise HTTPException(status_code=500, detail=str(e))


