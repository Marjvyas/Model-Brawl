HISTORY_DIR = os.path.join(UPLOAD_DIR, ".history")
os.makedirs(HISTORY_DIR, exist_ok=True)

def _get_history_folder(stored_as: str) -> str:
    safe_stored_as = os.path.basename(stored_as)
    folder = os.path.join(HISTORY_DIR, safe_stored_as)
    os.makedirs(folder, exist_ok=True)
    return folder

def _get_history_meta_path(stored_as: str) -> str:
    return os.path.join(_get_history_folder(stored_as), "history.json")

def _load_history_meta(stored_as: str) -> dict:
    meta_path = _get_history_meta_path(stored_as)
    if os.path.exists(meta_path):
        try:
            with open(meta_path, "r", encoding="utf-8") as f:
                return json.load(f)
        except Exception:
            pass
    return {"steps": [], "current_index": -1}

def _save_history_meta(stored_as: str, meta: dict):
    meta_path = _get_history_meta_path(stored_as)
    # Add last_modified timestamp if not present
    if "last_modified" not in meta:
        meta["last_modified"] = time.time()
    with open(meta_path, "w", encoding="utf-8") as f:
        json.dump(meta, f, indent=2)

def _record_dataset_snapshot(stored_as: str, action_desc: str, df: pd.DataFrame,
                             code: str = None, origin: str = "ui", cells: list = None):
    """
    Save a snapshot of the dataset AFTER an action, plus (optionally) the Python
    code that produced it. The code is what lets the Python Notebook rebuild its
    state by replaying every step in order:
        origin="ui"       -> a button in the app (delete column, change dtype...)
        origin="notebook" -> cells the user committed from the notebook
    """
    safe_stored_as = os.path.basename(stored_as)
    folder = _get_history_folder(safe_stored_as)
    meta = _load_history_meta(safe_stored_as)
    current_idx = meta.get("current_index", -1)
    steps = meta.get("steps", [])

    # Truncate forward steps if user performed an action after some undos
    if 0 <= current_idx < len(steps) - 1:
        for s in steps[current_idx + 1:]:
            old_snap = os.path.join(folder, s.get("file", ""))
            if os.path.exists(old_snap):
                try:
                    os.remove(old_snap)
                except Exception:
                    pass
        steps = steps[:current_idx + 1]

    new_step_id = len(steps)
    snap_filename = f"snap_{new_step_id}.csv"
    snap_path = os.path.join(folder, snap_filename)
    df.to_csv(snap_path, index=False)

    steps.append({
        "step_id": new_step_id,
        "file": snap_filename,
        "action": action_desc,
        "timestamp": time.time(),
        "columns": list(df.columns),
        "rows": int(len(df)),
        "origin": origin,
        "code": code,
        "cells": cells,
    })
    meta["steps"] = steps
    meta["current_index"] = len(steps) - 1
    meta["last_modified"] = time.time()  # Always update last_modified
    _save_history_meta(safe_stored_as, meta)

def _undo_dataset_snapshot(stored_as: str) -> tuple:
    safe_stored_as = os.path.basename(stored_as)
    folder = _get_history_folder(safe_stored_as)
    meta = _load_history_meta(safe_stored_as)
    current_idx = meta.get("current_index", -1)
    steps = meta.get("steps", [])

    if current_idx <= 0 or not steps:
        main_file_path = os.path.join(UPLOAD_DIR, safe_stored_as)
        bak_path = main_file_path + ".bak"
        if os.path.exists(bak_path):
            shutil.copy2(bak_path, main_file_path)
            df = _read_csv_safe(main_file_path)
            return df, "Reverted from backup"
        raise ValueError("No actions to undo.")

    undone_action = steps[current_idx]["action"]
    new_idx = current_idx - 1
    target_snap_file = os.path.join(folder, steps[new_idx]["file"])
    if not os.path.exists(target_snap_file):
        raise FileNotFoundError("Snapshot file not found.")

    df = _read_csv_safe(target_snap_file)
    main_file_path = os.path.join(UPLOAD_DIR, safe_stored_as)
    df.to_csv(main_file_path, index=False)

    meta["current_index"] = new_idx
    _save_history_meta(safe_stored_as, meta)
    return df, undone_action

def _redo_dataset_snapshot(stored_as: str) -> tuple:
    safe_stored_as = os.path.basename(stored_as)
    folder = _get_history_folder(safe_stored_as)
    meta = _load_history_meta(safe_stored_as)
    current_idx = meta.get("current_index", -1)
    steps = meta.get("steps", [])

    if current_idx >= len(steps) - 1 or current_idx < 0:
        raise ValueError("No actions to redo.")

    new_idx = current_idx + 1
    target_snap_file = os.path.join(folder, steps[new_idx]["file"])
    if not os.path.exists(target_snap_file):
        raise FileNotFoundError("Snapshot file not found.")

    df = _read_csv_safe(target_snap_file)
    main_file_path = os.path.join(UPLOAD_DIR, safe_stored_as)
    df.to_csv(main_file_path, index=False)

    meta["current_index"] = new_idx
    _save_history_meta(safe_stored_as, meta)
    redone_action = steps[new_idx]["action"]
    return df, redone_action

def _reset_dataset_snapshot(stored_as: str) -> tuple:
    safe_stored_as = os.path.basename(stored_as)
    folder = _get_history_folder(safe_stored_as)
    meta = _load_history_meta(safe_stored_as)
    steps = meta.get("steps", [])

    if not steps:
        raise ValueError("No history available to reset.")

    target_snap_file = os.path.join(folder, steps[0]["file"])
    if not os.path.exists(target_snap_file):
        raise FileNotFoundError("Initial snapshot file not found.")

    df = _read_csv_safe(target_snap_file)
    main_file_path = os.path.join(UPLOAD_DIR, safe_stored_as)
    df.to_csv(main_file_path, index=False)

    _record_dataset_snapshot(safe_stored_as, "Reset dataset to original", df,
                             code="df = _base_df.copy()")
    return df, "Reset dataset to original"

def _build_dataset_response(df: pd.DataFrame, stored_as: str, filename: str = None) -> dict:
    safe_stored_as = os.path.basename(stored_as)
    if filename is None:
        filename = safe_stored_as.split("_", 1)[1] if "_" in safe_stored_as else safe_stored_as

    target_col = df.columns[-1] if len(df.columns) > 0 else ""
    col_info = []
    for col in df.columns:
        col_info.append({
            "name": col,
            "dtype": str(df[col].dtype),
            "null_count": int(df[col].isna().sum()),
            "unique_count": int(df[col].nunique())
        })

    preview_rows = json.loads(df.head(5).to_json(orient="records"))
    meta = _load_history_meta(safe_stored_as)
    current_idx = meta.get("current_index", -1)
    steps = meta.get("steps", [])

    return {
        "filename": filename,
        "stored_as": safe_stored_as,
        "rows": df.shape[0],
        "columns": df.shape[1],
        "target_column": target_col,
        "memory_usage_kb": round(df.memory_usage(deep=True).sum() / 1024, 2),
        "column_info": col_info,
        "preview_rows": preview_rows,
        "can_undo": current_idx > 0,
        "can_redo": 0 <= current_idx < len(steps) - 1,
        "history": [s["action"] for s in steps[:current_idx + 1]],
        "last_action": steps[current_idx]["action"] if 0 <= current_idx < len(steps) else None,
    }


