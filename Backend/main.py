def _read_csv_safe(file_path: str) -> pd.DataFrame:
    """
    Read a CSV with robust encoding fallback and coerce numeric columns.
    Tries utf-8 -> latin-1 -> unicode_escape. After reading, converts any
    string columns that are actually numeric back to numeric types to
    prevent pyarrow large_string errors in sklearn operations.
    """
    df = None
    for enc in ["utf-8", "latin-1", "unicode_escape"]:
        try:
            df = pd.read_csv(file_path, encoding=enc)
            break
        except (UnicodeDecodeError, UnicodeError):
            continue
        except Exception:
            raise

    if df is None:
        raise ValueError("Could not read the CSV with any supported encoding (utf-8, latin-1, unicode_escape).")

    return df


