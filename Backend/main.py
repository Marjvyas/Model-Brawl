class RecalculateEDARequest(BaseModel):
    deleted_features: List[str]

@app.post("/api/recalculate_eda/{task_id}")
async def recalculate_eda(task_id: str, req: RecalculateEDARequest):
    """
    Recomputes the EDA payload (feature importance, correlation matrix,
    skewness tracker) from the CACHED training matrix with the user's
    excluded features removed. Fast — no re-preprocessing.
    Recipe changes are handled by /api/feature_forge instead, which
    re-runs Phase 1 + Phase 2 from the raw CSV and re-caches the parquet.
    """
    if task_id not in tasks:
        raise HTTPException(status_code=404, detail="Task not found.")

    task = tasks[task_id]
    cache_dir = os.path.join(UPLOAD_DIR, task_id)
    X_train_path = os.path.join(cache_dir, "X_train.parquet")
    if not os.path.exists(X_train_path):
        raise HTTPException(status_code=404, detail="Cached dataset not found. Please re-run the pipeline.")

    try:
        X_train = pd.read_parquet(X_train_path)
        y_train = pd.read_parquet(os.path.join(cache_dir, "y_train.parquet")).iloc[:, 0]

        cols_to_drop = [c for c in req.deleted_features if c in X_train.columns]
        if cols_to_drop:
            X_train = X_train.drop(columns=cols_to_drop)

        if X_train.shape[1] == 0:
            raise ValueError("Cannot recalculate EDA: every feature is excluded.")

        target_col = task.get("preprocessing_report", {}).get("target_column", "target")

        old_eda = task.get("results", {}).get("dataset_analysis", {}).get("eda_payload", {})
        # Keep only skewness entries for columns that still exist
        skewness_tracker = {
            k: v for k, v in old_eda.get("skewness_tracker", {}).items()
            if k in X_train.columns
        }

        new_eda_payload = ml_pipeline.calculate_eda(
            X_train, y_train, target_col, skewness_tracker=skewness_tracker
        )

        if "results" in task and "dataset_analysis" in task["results"]:
            task["results"]["dataset_analysis"]["eda_payload"] = new_eda_payload

        return new_eda_payload

    except ValueError as e:
        raise HTTPException(status_code=400, detail=str(e))
    except Exception as e:
        import traceback
        traceback.print_exc()
        raise HTTPException(status_code=500, detail=str(e))


