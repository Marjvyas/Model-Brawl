@app.post("/api/prepare")
def prepare_data(body: dict):
    stored_as = body.get("stored_as")
    if not stored_as:
        raise HTTPException(status_code=400, detail="Missing 'stored_as' field.")
        
    file_path = os.path.join(UPLOAD_DIR, stored_as)
    if not os.path.exists(file_path):
        raise HTTPException(status_code=404, detail="Uploaded file not found.")
        
    try:
        df = _read_csv_safe(file_path)
        
        # Run Phase 1
        (X_train_cat, X_test_cat, X_train_cont, X_test_cont,
         y_train, y_test, categorical_cols, continuous_cols, target_col,
         original_shape, duplicates_removed, null_target_rows,
         columns_dropped_high_null, target_skewness, target_transform_applied, final_shape, index_cols_to_drop) = ml_pipeline.imp_phase1(df)
         
        # Cache Phase 1 results so we don't have to run it again
        # Actually, if we just run it again in the background task, it's safer and less state to manage.
        # But wait! If we run it again, the random split is seeded (random_state=42) so it's deterministic.
        # So we can just fetch unique categories here and return them.
        
        cat_info = {}
        for col in categorical_cols:
            # Get up to 20 unique values for ordinal ordering
            unique_vals = X_train_cat[col].unique().tolist()
            if len(unique_vals) > 50:
                unique_vals = unique_vals[:50]
            cat_info[col] = unique_vals
            
        return {"categorical_cols": categorical_cols, "cat_info": cat_info}
        
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))

@app.post("/api/run")
async def run_pipeline(body: dict):
    """
    Launch the ML pipeline as a background task.
    """
    stored_as = body.get("stored_as")
    encoding_config = body.get("encoding_config", {})
    recipe_book = body.get("recipe_book", [])
    if not stored_as:
        raise HTTPException(status_code=400, detail="Missing 'stored_as' field.")

    file_path = os.path.join(UPLOAD_DIR, stored_as)
    if not os.path.exists(file_path):
        raise HTTPException(status_code=404, detail="Uploaded file not found. Please re-upload.")

    task_id = str(uuid.uuid4())
    tasks[task_id] = {
        "status": "queued",
        "progress": 0,
        "step": "Queued",
        "results": None,
        "error": None,
        "start_time": time.time(),
        "encoding_config": encoding_config,
        "recipe_book": recipe_book,
        "stored_as": stored_as
    }

    import threading
    thread = threading.Thread(target=_run_eda_task, args=(task_id, file_path, stored_as), daemon=True)
    thread.start()

    return {"task_id": task_id}


