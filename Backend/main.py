def _run_train_task(task_id: str, mode: str = "standard", deleted_features: list = None):
    """Phase 2: Model Tournament & Final Exam"""
    log_lines = []
    def log(msg):
        log_lines.append(str(msg))
        
    try:
        tasks[task_id]["step"] = "Loading cached data..."
        cache_dir = os.path.join(UPLOAD_DIR, task_id)
        
        import pandas as pd
        X_train = pd.read_parquet(os.path.join(cache_dir, "X_train.parquet"))
        X_test = pd.read_parquet(os.path.join(cache_dir, "X_test.parquet"))
        y_train = pd.read_parquet(os.path.join(cache_dir, "y_train.parquet")).iloc[:, 0]
        y_test = pd.read_parquet(os.path.join(cache_dir, "y_test.parquet")).iloc[:, 0]
        
        if deleted_features:
            cols_to_drop = [c for c in deleted_features if c in X_train.columns]
            if cols_to_drop:
                log(f"User manually excluded {len(cols_to_drop)} feature(s) before tournament: {', '.join(cols_to_drop)}")
                X_train = X_train.drop(columns=cols_to_drop)
                X_test = X_test.drop(columns=cols_to_drop)
                
                if X_train.shape[1] == 0:
                    raise ValueError("Cannot run tournament: All features were deleted!")

        # Remember which features the user excluded so a later single-model
        # re-evaluation (/api/model_details) uses the exact same feature set
        tasks[task_id]["excluded_features"] = deleted_features or []
        

        
        preprocessing_report = tasks[task_id].get("preprocessing_report", {})

        tasks[task_id]["progress"] = 30
        tasks[task_id]["status"] = "training"
        tasks[task_id]["step"] = "Training & evaluating 9 models..."

        # ── Step 3: Model Tournament ──
        def on_model_done(name, done, total):
            pct = 30 + int((done / total) * 45)  # 30% → 75%
            tasks[task_id]["progress"] = pct
            tasks[task_id]["step"] = f"Trained {done}/{total}: {name}"

        leaderboard, winning_model, recommendation_text, _ = ml_pipeline.ultimate_model_selector(
            X_train, y_train, log=log, on_model_done=on_model_done, mode=mode
        )

        tasks[task_id]["progress"] = 75
        tasks[task_id]["status"] = "evaluating"
        tasks[task_id]["step"] = "Final evaluation on held-out data..."

        winning_name = leaderboard.loc[0, "Model"]

        # ── Step 4: Final Exam ──
        _, final_metrics = ml_pipeline.final_exam(
            winning_name, winning_model, X_train, y_train, X_test, y_test, 
            target_transform_applied=preprocessing_report.get("target_transform_applied"), log=log
        )

        elapsed = round(time.time() - tasks[task_id]["start_time"], 2)
        log(f"\nPipeline completed successfully in {elapsed} seconds.")

        # ── Build leaderboard JSON ──
        leaderboard_list = []
        for idx, row in leaderboard.iterrows():
            leaderboard_list.append({
                "rank": idx + 1,
                "model": row["Model"],
                "cv_r2_mean": round(float(row["CV_R2_Mean"]), 4),
                "cv_r2_std": round(float(row["CV_R2_Std"]), 6),
            })

        # ── Assemble final results ──
        tasks[task_id]["results"] = {
            "task_id": task_id,
            "status": "complete",
            "dataset_analysis": preprocessing_report,
            "leaderboard": leaderboard_list,
            "best_model": {
                "name": winning_name,
                "cv_r2": leaderboard_list[0]["cv_r2_mean"],
                "final_r2": final_metrics["final_r2"],
                "final_rmse": final_metrics["final_rmse"],
                "recommendation": recommendation_text,
                "verdict": final_metrics["verdict"],
                "visuals": final_metrics.get("visuals", {})
            },
            "pipeline_log": "\n".join(log_lines),
            "execution_time_seconds": elapsed,
        }
        tasks[task_id]["status"] = "complete"
        tasks[task_id]["progress"] = 100
        tasks[task_id]["step"] = "Complete"

    except Exception as e:
        tasks[task_id]["status"] = "error"
        tasks[task_id]["error"] = str(e)
        tasks[task_id]["step"] = "Error"
        tasks[task_id]["progress"] = 0
        # Still save log for debugging
